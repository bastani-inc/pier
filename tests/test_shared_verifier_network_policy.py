"""A shared verifier can carry a network policy of its own.

The verifier runs inside the agent's container, so the policy is enforced by
the egress proxy authenticating the two phases as two htpasswd users, each with
its own ACL files. The single-user output is pinned byte-for-byte: a task that
declares no verifier network policy must produce exactly the proxy config and
exec environments pier produced before per-phase policy existed.
"""

