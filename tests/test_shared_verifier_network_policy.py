AGENT_ALLOWLIST = NetworkAllowlist(
    domains=["api.example.com"], ip_entries=["10.0.0.0/8"]
)
VERIFIER_ALLOWLIST = NetworkAllowlist(domains=["pypi.org"], ip_entries=["192.0.2.0/24"])

# Generated by pier at commit 9e56148, before per-phase verifier policy existed.
# Any change to this string changes the proxy every existing task runs behind.
HEAD_SINGLE_USER_SCRIPT = r"""#!/usr/bin/env bash
set -eu

printf '%s' "$ALLOWLIST_DOMAINS" | tr ',' '\n' | sed '/^[[:space:]]*$/d' \
  > /tmp/allowed_domains.txt
printf '%s' "$ALLOWLIST_IPS" | tr ',' '\n' | sed '/^[[:space:]]*$/d' \
  > /tmp/allowed_ips.txt

htpasswd -bc /tmp/squid.passwd agent "$PROXY_TOKEN"

cat > /tmp/squid.conf <<'EOF'
http_port 0.0.0.0:8080
pid_filename /tmp/squid.pid
coredump_dir /tmp

auth_param basic program /usr/lib/squid/basic_ncsa_auth /tmp/squid.passwd
auth_param basic realm PierPolicyProxy
acl authenticated proxy_auth REQUIRED

acl SSL_ports port 443
acl Safe_ports port 80 443
acl CONNECT method CONNECT
acl allowed_domains dstdomain "/tmp/allowed_domains.txt"
acl allowed_ips dst "/tmp/allowed_ips.txt"

http_access deny !Safe_ports
http_access deny CONNECT !SSL_ports
http_access allow authenticated allowed_domains
http_access allow authenticated allowed_ips
http_access deny all

cache deny all
access_log stdio:/tmp/squid_access.log
cache_log /tmp/squid_cache.log
log_mime_hdrs off
shutdown_lifetime 1 seconds
EOF

exec squid -N -f /tmp/squid.conf -d 1
"""


def _squid_conf(script: str) -> list[str]:
    """The squid.conf heredoc lines out of a bootstrap script."""
    body = script.split("cat > /tmp/squid.conf <<'EOF'\n", 1)[1]
    return body.split("\nEOF\n", 1)[0].splitlines()


