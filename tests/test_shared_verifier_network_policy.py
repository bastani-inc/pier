@pytest.mark.parametrize(
    "verifier_allowlist", [None, NetworkAllowlist(), NetworkAllowlist(domains=[])]
)
def test_single_user_bootstrap_script_is_byte_identical(verifier_allowlist):
    assert (
        squid_bootstrap_command(AGENT_ALLOWLIST, verifier_allowlist)
        == HEAD_SINGLE_USER_SCRIPT
    )


def test_single_user_proxy_policy_env_carries_no_verifier_keys():
    assert proxy_policy_env(AGENT_ALLOWLIST, "tok") == {
        "PROXY_TOKEN": "tok",
        "ALLOWLIST_DOMAINS": "api.example.com",
        "ALLOWLIST_IPS": "10.0.0.0/8",
    }
    assert proxy_policy_env(AGENT_ALLOWLIST, "tok", NetworkAllowlist(), None) == {
        "PROXY_TOKEN": "tok",
        "ALLOWLIST_DOMAINS": "api.example.com",
        "ALLOWLIST_IPS": "10.0.0.0/8",
    }


def test_single_user_compose_file_is_byte_identical(tmp_path):
    args = {
        "path": tmp_path / "compose.json",
        "proxy_dir": tmp_path / "proxy",
        "allowlist": AGENT_ALLOWLIST,
        "token": "secret",
    }
    without = write_docker_proxy_compose(**args).read_text()
    with_empty = write_docker_proxy_compose(
        **args, verifier_allowlist=NetworkAllowlist(), verifier_token=None
    ).read_text()

    assert without == with_empty
    assert (tmp_path / "proxy" / "start-squid.sh").read_text() == (
        HEAD_SINGLE_USER_SCRIPT
    )
    compose = json.loads(without)
    env = compose["services"][EGRESS_PROXY_SERVICE]["environment"]
    assert not any(key.startswith("VERIFIER_") for key in env)


def test_agent_proxy_url_still_names_the_agent_user():
    assert proxy_environment("secret", "host")["HTTP_PROXY"] == (
        "http://agent:secret@host:8080"
    )


