SHARED_VERIFIER_POLICY_TOML = """
[agent]
timeout_sec = 10.0
network_mode = "no-network"
[verifier]
timeout_sec = 10.0
network_mode = "allowlist"
allowed_hosts = ["deps.internal.example"]
[environment]
network_mode = "no-network"
"""

SAME_MODE_SHARED_TOML = """
[agent]
timeout_sec = 10.0
[verifier]
timeout_sec = 10.0
[environment]
network_mode = "allowlist"
allowed_hosts = ["deps.internal.example"]
"""

VERIFIER_PROXY_URL = "http://verifier:secret@pier-egress-proxy:8080"
AGENT_PROXY_URL = "http://agent:secret@pier-egress-proxy:8080"


def _task(tmp: Path, toml: str) -> Path:
    task_dir = tmp / "task"
    task_dir.mkdir()
    (task_dir / "task.toml").write_text(toml)
    (task_dir / "instruction.md").write_text("Do nothing.\n")
    env_dir = task_dir / "environment"
    env_dir.mkdir()
    (env_dir / "Dockerfile").write_text("FROM ubuntu:24.04\n")
    tests_dir = task_dir / "tests"
    tests_dir.mkdir()
    (tests_dir / "Dockerfile").write_text("FROM ubuntu:24.04\n")
    (tests_dir / "test.sh").write_text("#!/bin/bash\nexit 0\n")
    return task_dir


async def _run(tmp: Path, toml: str):
    trials_dir = tmp / "trials"
    trials_dir.mkdir()
    agent_env = _make_env(mounted=True)
    agent_env.verifier_process_env.side_effect = lambda process_env: {
        **(process_env or {}),
        "HTTP_PROXY": VERIFIER_PROXY_URL,
    }
    agent_env.agent_process_env.side_effect = lambda process_env: {
        **(process_env or {}),
        "HTTP_PROXY": AGENT_PROXY_URL,
    }
    fake_create, calls = _make_factory_recorder(agent_env, [])
    await _run_trial(
        _task(tmp, toml),
        trials_dir,
        fake_create,
        agent=_mock_agent(NetworkAllowlist(domains=["api.model.example"])),
    )
    return calls, agent_env


@run_async
async def test_shared_verifier_policy_reaches_the_environment_and_the_command():
    with tempfile.TemporaryDirectory() as tmp:
        calls, agent_env = await _run(Path(tmp), SHARED_VERIFIER_POLICY_TOML)

        assert len(calls) == 1  # still one container
        assert calls[0]["verifier_network_allowlist"].domains == [
            "deps.internal.example"
        ]
        # The verifier's host is not in the agent's allowlist.
        assert calls[0]["network_allowlist"].domains == ["api.model.example"]
        exec_envs = [call.kwargs.get("env") for call in agent_env.exec.await_args_list]
        assert any(
            env is not None and env.get("HTTP_PROXY") == VERIFIER_PROXY_URL
            for env in exec_envs
        )
        agent_env.agent_process_env.assert_not_called()


@run_async
async def test_shared_verifier_inherits_baseline_proxy_env():
    with tempfile.TemporaryDirectory() as tmp:
        calls, agent_env = await _run(Path(tmp), SAME_MODE_SHARED_TOML)

        assert calls[0].get("verifier_network_allowlist") is None
        agent_env.verifier_process_env.assert_not_called()
        exec_envs = [call.kwargs.get("env") for call in agent_env.exec.await_args_list]
        assert any(
            env is not None and env.get("HTTP_PROXY") == AGENT_PROXY_URL
            for env in exec_envs
        )
