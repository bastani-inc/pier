def _docker_env(tmp_path: Path, allowlist, verifier_allowlist) -> DockerEnvironment:
    env = DockerEnvironment.__new__(DockerEnvironment)
    env.network_allowlist = allowlist
    env.verifier_network_allowlist = verifier_allowlist
    env.task_env_config = type("TaskEnv", (), {"has_public_network": False})()
    env.trial_paths = SimpleNamespace(trial_dir=tmp_path)
    env.environment_dir = tmp_path / "environment"  # Dockerfile task, no compose
    env._egress_proxy_env = {}
    env._verifier_proxy_env = {}
    env._egress_proxy_compose_path = None
    return env


def test_docker_provisions_two_users_only_with_a_verifier_policy(tmp_path):
    env = _docker_env(tmp_path, AGENT_ALLOWLIST, VERIFIER_ALLOWLIST)

    env._prepare_egress_proxy_compose()

    agent_env = env.agent_process_env(None)
    verifier_env = env.verifier_process_env(None)
    assert agent_env["HTTP_PROXY"].startswith("http://agent:")
    assert verifier_env["HTTP_PROXY"].startswith("http://verifier:")
    assert agent_env["HTTP_PROXY"] != verifier_env["HTTP_PROXY"]
    compose = json.loads(env._egress_proxy_compose_path.read_text())
    proxy = compose["services"][EGRESS_PROXY_SERVICE]["environment"]
    assert proxy["VERIFIER_ALLOWLIST_DOMAINS"] == "pypi.org"
    assert proxy["VERIFIER_PROXY_TOKEN"] != proxy["PROXY_TOKEN"]


def test_docker_without_verifier_policy_has_no_verifier_credentials(tmp_path):
    env = _docker_env(tmp_path, AGENT_ALLOWLIST, NetworkAllowlist())

    env._prepare_egress_proxy_compose()

    assert env.verifier_process_env({"A": "b"}) == {"A": "b"}
    assert (tmp_path / "egress-proxy" / "start-squid.sh").read_text() == (
        HEAD_SINGLE_USER_SCRIPT
    )


def test_docker_starts_the_proxy_for_a_verifier_only_allowlist(tmp_path):
    """agent='no-network' + verifier='allowlist': the proxy exists for one user."""
    env = _docker_env(tmp_path, NetworkAllowlist(), VERIFIER_ALLOWLIST)

    env._prepare_egress_proxy_compose()

    assert env._egress_proxy_compose_path is not None
    assert env.verifier_process_env(None)["HTTP_PROXY"].startswith("http://verifier:")


def test_modal_verifier_process_env_merges_verifier_credentials():
    env = ModalEnvironment.__new__(ModalEnvironment)
    env._egress_proxy_env = proxy_environment("agent-tok", "r123.modal.host", 12345)
    env._verifier_proxy_env = proxy_environment(
        "verifier-tok", "r123.modal.host", 12345, user=PROXY_VERIFIER_USER
    )

    assert env.verifier_process_env({"X": "1"}) == {
        **env._verifier_proxy_env,
        "X": "1",
    }
    assert "verifier-tok" not in json.dumps(env.agent_process_env(None))


def test_environment_without_phase_scoped_egress_rejects_the_policy():
    env = DaytonaEnvironment.__new__(DaytonaEnvironment)
    env._compose_mode = False
    env.agent_install_spec = None
    env.task_env_config = type("TaskEnv", (), {"has_public_network": False})()
    env.network_allowlist = NetworkAllowlist()
    env.verifier_network_allowlist = VERIFIER_ALLOWLIST
    env.logger = logging.getLogger("test")

    assert env.capabilities.phase_scoped_egress is False
    with pytest.raises(ValueError, match="per-phase egress"):
        BaseEnvironment._validate_agent_setup_options(env)


