def test_two_user_script_provisions_a_second_user_and_acl_files():
    script = squid_bootstrap_command(AGENT_ALLOWLIST, VERIFIER_ALLOWLIST)

    assert 'htpasswd -bc /tmp/squid.passwd agent "$PROXY_TOKEN"' in script
    assert 'htpasswd -b /tmp/squid.passwd verifier "$VERIFIER_PROXY_TOKEN"' in script
    assert "/tmp/allowed_domains_verifier.txt" in script
    assert "/tmp/allowed_ips_verifier.txt" in script


def test_two_user_rules_are_scoped_per_proxy_user():
    conf = _squid_conf(squid_bootstrap_command(AGENT_ALLOWLIST, VERIFIER_ALLOWLIST))

    assert "acl agent_user proxy_auth agent" in conf
    assert "acl verifier_user proxy_auth verifier" in conf
    allows = [line for line in conf if line.startswith("http_access allow")]
    assert allows == [
        "http_access allow agent_user allowed_domains",
        "http_access allow agent_user allowed_ips",
        "http_access allow verifier_user allowed_domains_verifier",
        "http_access allow verifier_user allowed_ips_verifier",
    ]


def test_verifier_only_policy_grants_the_agent_nothing():
    """A no-network agent phase around an allowlisted verifier phase."""
    conf = _squid_conf(squid_bootstrap_command(NetworkAllowlist(), VERIFIER_ALLOWLIST))

    allows = [line for line in conf if line.startswith("http_access allow")]
    assert allows == [
        "http_access allow verifier_user allowed_domains_verifier",
        "http_access allow verifier_user allowed_ips_verifier",
    ]
    assert not any("agent_user" in line for line in conf)


def test_two_user_policy_env_carries_both_halves():
    env = proxy_policy_env(
        AGENT_ALLOWLIST, "agent-tok", VERIFIER_ALLOWLIST, "verifier-tok"
    )

    assert env["PROXY_TOKEN"] == "agent-tok"
    assert env["VERIFIER_PROXY_TOKEN"] == "verifier-tok"
    assert env["VERIFIER_ALLOWLIST_DOMAINS"] == "pypi.org"
    assert env["VERIFIER_ALLOWLIST_IPS"] == "192.0.2.0/24"


def test_verifier_proxy_url_names_the_verifier_user():
    assert (
        proxy_environment("secret", "host", user=PROXY_VERIFIER_USER)["HTTP_PROXY"]
        == "http://verifier:secret@host:8080"
    )


# --------------------------------------------------------------------------
# Hardening: nothing but the two phase allowlists is reachable.
# --------------------------------------------------------------------------


@pytest.mark.parametrize("verifier_allowlist", [NetworkAllowlist(), VERIFIER_ALLOWLIST])
def test_squid_config_denies_cache_manager_to_proxy_users(verifier_allowlist):
    conf = _squid_conf(squid_bootstrap_command(AGENT_ALLOWLIST, verifier_allowlist))
    access = [line for line in conf if line.startswith("http_access")]

    # Nothing grants the cache manager, and deny-all is the last word: an allow
    # rule added after it would be unreachable, so squid administration stays
    # closed to every authenticated phase.
    assert not any("manager" in line for line in conf)
    assert access[-1] == "http_access deny all"
    # Every allow names the proxy user it belongs to, so no rule is anonymous.
    assert all(
        line.split()[2] in {"authenticated", "agent_user", "verifier_user"}
        for line in access
        if line.startswith("http_access allow")
    )


